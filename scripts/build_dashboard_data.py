#!/usr/bin/env python3
"""
Reads the MapReduce / Mahout output files in results/ and writes
dashboard/data.js so the dashboard can show them.

Run from the project root after copying new results:
    python3 scripts/build_dashboard_data.py
"""

import os
import re
import json

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESULTS = os.path.join(ROOT, "results")
OUT_FILE = os.path.join(ROOT, "dashboard", "data.js")


def read_counts(filename):
    """Reads 'PREFIX,key<TAB>count' lines and returns [[key, count], ...]."""
    path = os.path.join(RESULTS, filename)
    if not os.path.exists(path):
        return None

    rows = {}
    with open(path, encoding="utf-8", errors="ignore") as f:
        for line in f:
            line = line.strip()
            if not line or "\t" not in line:
                continue
            key, value = line.rsplit("\t", 1)
            key = key.split(",", 1)[1] if "," in key else key
            try:
                rows[key] = int(value)
            except ValueError:
                continue

    return sorted(rows.items(), key=lambda kv: kv[1], reverse=True)


def read_summary(filename):
    """Splits traffic summary lines into LABEL / ATTACK_CATEGORY / PROTOCOL groups."""
    path = os.path.join(RESULTS, filename)
    if not os.path.exists(path):
        return None

    groups = {}
    with open(path, encoding="utf-8", errors="ignore") as f:
        for line in f:
            line = line.strip()
            if "\t" not in line or "," not in line:
                continue
            key, value = line.rsplit("\t", 1)
            group, name = key.split(",", 1)
            groups.setdefault(group, []).append([name, int(value)])

    for group in groups:
        groups[group].sort(key=lambda kv: kv[1], reverse=True)
    return groups


def read_rf_evaluation(filename):
    """Picks accuracy, kappa and the raw text from Mahout testforest output."""
    path = os.path.join(RESULTS, filename)
    if not os.path.exists(path):
        return None

    with open(path, encoding="utf-8", errors="ignore") as f:
        text = f.read()

    result = {"raw": text[-6000:]}

    match = re.search(r"Correctly Classified Instances\s*:\s*(\d+)\s+([\d.]+)%", text)
    if match:
        result["correct"] = int(match.group(1))
        result["accuracy"] = float(match.group(2))

    match = re.search(r"Incorrectly Classified Instances\s*:\s*(\d+)", text)
    if match:
        result["incorrect"] = int(match.group(1))

    match = re.search(r"Kappa\s*:?\s*([-\d.]+)", text)
    if match:
        result["kappa"] = float(match.group(1))

    return result


data = {
    "attack_sources": read_counts("attack_sources.txt"),
    "top_10_attack_sources": read_counts("top_10_attack_sources.txt"),
    "attack_services": read_counts("attack_services.txt"),
    "attack_destination_ports": read_counts("attack_destination_ports.txt"),
    "traffic_summary_sample": read_summary("traffic_summary_sample.txt"),
    "traffic_summary": read_summary("traffic_summary.txt"),
    "random_forest": read_rf_evaluation("random_forest_evaluation.txt"),
    "random_forest_sample": read_rf_evaluation("random_forest_sample_evaluation.txt"),
}

os.makedirs(os.path.dirname(OUT_FILE), exist_ok=True)
with open(OUT_FILE, "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/build_dashboard_data.py from results/*.txt\n")
    f.write("window.DASHBOARD_DATA = ")
    json.dump(data, f, separators=(",", ":"))
    f.write(";\n")

for name, value in data.items():
    status = "found" if value else "not found"
    print(f"{name:28s} {status}")
print("Written:", OUT_FILE)
